#Requires -Version 5.1
<#
.SYNOPSIS
    Regenerates src/Obfuscar/BaitText.Data.cs from a plaintext word list.

.DESCRIPTION
    The bait and safeguard word lists must never appear in this repository as
    readable text. This script converts a plaintext list into:

      * Pool - one shuffled character table containing every distinct char
      * per-word base64 blobs, each a packed sequence of ushort indices
        into Pool

    Obfuscar reassembles the words at runtime (see BaitText.cs). Keep the
    plaintext list outside source control; the default path
    build/bait-words.txt is covered by .gitignore.

.INPUT FILE FORMAT
    # comment
    @@TableName
    one entry per line
    escapes: \\ for backslash, \n for newline, \t for tab

.EXAMPLE
    powershell -File build/Encode-BaitText.ps1
    powershell -File build/Encode-BaitText.ps1 -ListFile D:\secure\words.txt
#>
[CmdletBinding()]
param(
    [string]$ListFile,
    [string]$OutFile,
    [int]$ShuffleSeed = 7919
)

$ErrorActionPreference = 'Stop'

$scriptDir = $PSScriptRoot
if (-not $scriptDir) { $scriptDir = Split-Path -Parent $PSCommandPath }
if (-not $scriptDir) { $scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $ListFile) { $ListFile = Join-Path $scriptDir 'bait-words.txt' }
if (-not $OutFile) { $OutFile = Join-Path $scriptDir '..\src\Obfuscar\BaitText.Data.cs' }

if (-not (Test-Path $ListFile)) {
    throw "Word list not found: $ListFile`nProvide -ListFile, or create the default bait-words.txt next to this script."
}
$ListFile = (Resolve-Path $ListFile).Path

# ---------- parse the plaintext list ----------
$tables = [ordered]@{}
$current = $null
$lineNo = 0
foreach ($raw in [System.IO.File]::ReadAllLines($ListFile, [System.Text.Encoding]::UTF8)) {
    $lineNo++
    $line = $raw.TrimEnd("`r")
    if ($line -eq '' -or $line -match '^\s*#') { continue }
    if ($line -match '^@@([A-Za-z0-9_]+)\s*$') {
        $current = $Matches[1]
        if ($tables.Contains($current)) { throw "Duplicate table @@$current at line $lineNo" }
        $tables[$current] = New-Object 'System.Collections.Generic.List[string]'
        continue
    }
    if ($null -eq $current) { throw "Entry outside any @@table at line ${lineNo}: $line" }
    # unescape: \\ first (via NUL placeholder), then \n and \t, then restore
    $entry = $line -replace '\\\\', "`0"
    $entry = $entry -replace '\\n', "`n" -replace '\\t', "`t"
    $entry = $entry -replace "`0", '\'
    $tables[$current].Add($entry)
}
if ($tables.Count -eq 0) { throw "No @@tables found in $ListFile" }

# ---------- build the shuffled character pool ----------
$seen = @{}
foreach ($entries in $tables.Values) {
    foreach ($word in $entries) {
        foreach ($c in $word.ToCharArray()) { $seen[[int]$c] = $true }
    }
}
$chars = @($seen.Keys | Sort-Object)
if ($chars.Count -gt 65536) { throw 'Character pool cannot exceed 65536 entries' }

$rng = New-Object System.Random($ShuffleSeed)
for ($i = $chars.Count - 1; $i -gt 0; $i--) {
    $j = $rng.Next($i + 1)
    $tmp = $chars[$i]; $chars[$i] = $chars[$j]; $chars[$j] = $tmp
}
$indexOf = @{}
for ($i = 0; $i -lt $chars.Count; $i++) { $indexOf[[int]$chars[$i]] = $i }
$pool = -join ($chars | ForEach-Object { [char]$_ })

function Encode-Entry([string]$word) {
    $bytes = New-Object byte[] ($word.Length * 2)
    for ($i = 0; $i -lt $word.Length; $i++) {
        $v = $indexOf[[int]$word[$i]]
        $bytes[$i * 2] = [byte]($v -band 0xFF)
        $bytes[$i * 2 + 1] = [byte]($v -shr 8)
    }
    [Convert]::ToBase64String($bytes)
}

# emits a pure-ASCII C# string literal body
function Escape-Literal([string]$s) {
    $sb = New-Object System.Text.StringBuilder
    foreach ($c in $s.ToCharArray()) {
        $v = [int]$c
        if ($c -eq '\') { [void]$sb.Append('\\') }
        elseif ($c -eq '"') { [void]$sb.Append('\"') }
        elseif ($v -eq 9) { [void]$sb.Append('\t') }
        elseif ($v -eq 10) { [void]$sb.Append('\n') }
        elseif ($v -eq 13) { [void]$sb.Append('\r') }
        elseif ($v -lt 32 -or $v -gt 126) { [void]$sb.Append(('\u{0:x4}' -f $v)) }
        else { [void]$sb.Append($c) }
    }
    $sb.ToString()
}

# ---------- emit BaitText.Data.cs ----------
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// <auto-generated/>')
[void]$out.AppendLine('// Generated by build/Encode-BaitText.ps1 from a plaintext word list that')
[void]$out.AppendLine('// is intentionally not committed. Do not edit by hand - rerun the script.')
[void]$out.AppendLine('namespace Obfuscar')
[void]$out.AppendLine('{')
[void]$out.AppendLine('    internal static partial class BaitText')
[void]$out.AppendLine('    {')
[void]$out.AppendLine(('        private const string Pool = "{0}";' -f (Escape-Literal $pool)))

foreach ($name in $tables.Keys) {
    $entries = $tables[$name]
    if ($entries.Count -eq 0) { Write-Warning "Table @@$name is empty" }
    [void]$out.AppendLine('')
    [void]$out.AppendLine(('        private static readonly string[] {0}Data =' -f $name))
    [void]$out.AppendLine('        {')
    $dupe = @{}
    foreach ($word in $entries) {
        if ($dupe.ContainsKey($word)) { Write-Warning "Duplicate entry in @@${name}: $($word.Substring(0, [Math]::Min(40, $word.Length)))" }
        $dupe[$word] = $true
        [void]$out.AppendLine(('            "{0}",' -f (Encode-Entry $word)))
    }
    [void]$out.AppendLine('        };')
}
[void]$out.AppendLine('    }')
[void]$out.AppendLine('}')

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($OutFile, $out.ToString(), $utf8NoBom)

$total = 0
foreach ($entries in $tables.Values) { $total += $entries.Count }
Write-Host "Wrote $OutFile : $($tables.Count) tables, $total entries, pool of $($chars.Count) chars"
